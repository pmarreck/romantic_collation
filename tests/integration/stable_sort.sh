#!/usr/bin/env bash
# Stability is relative to the selected key, not raw bytes or another column.
set -u
CLI=${COLLATE_CLI:?the test runner must supply a packaged CLI}
PASS=0 FAIL=0
check() {
	local name=$1 expected=$2 input=$3 actual status
	shift 3
	actual=$(printf '%s' "$input" | "$CLI" "$@")
	status=$?
	if [[ $status -eq 0 && $actual == "$expected" ]]; then
		PASS=$((PASS+1))
	else
		printf 'FAIL: %s (status %s): got %q, expected %q\n' "$name" "$status" "$actual" "$expected" >&2
		FAIL=$((FAIL+1))
	fi
}
check 'ascending whitespace ties preserve input order' $'a \na\t\nb' $'b\na \na\t\n'
check 'descending whitespace ties preserve input order' $'b\na\t\na ' $'a\t\nb\na \n' -r
check 'descending ties also preserve the opposite input order' $'b\na \na\t' $'a \nb\na\t\n' -r
check 'unique keeps first input spelling' $'a \nb' $'b\na \na\t\n' -u
check 'descending unique keeps the same first spelling' $'b\na ' $'b\na \na\t\n' -r -u
check 'Romanian canonical ties preserve input order' $'ș\nş' $'ș\nş\n'
check 'decimal ties preserve input order' $'7\n007\n8' $'8\n7\n007\n' -d
check 'scientific ties preserve input order' $'1e1\n10e0\n20' $'20\n1e1\n10e0\n' -s
check 'default leading zeros remain a real distinction' $'007\n07\n7' $'7\n007\n07\n'
check 'case remains a real distinction' $'apple\nApple' $'Apple\napple\n'
check 'reverse still reverses real case distinctions' $'Apple\napple' $'Apple\napple\n' -r
check 'selected-field ties preserve input order' $'b:1\na:1\nc:2' $'c:2\nb:1\na:1\n' -t: -k2
check 'descending selected-field ties preserve input order' $'c:2\nb:1\na:1' $'b:1\nc:2\na:1\n' -t: -k2 -r
check 'unique selected fields retain first input record' $'b:1\nc:2' $'c:2\nb:1\na:1\n' -t: -k2 -u
check 'descending unique fields retain the same records' $'c:2\nb:1' $'c:2\nb:1\na:1\n' -t: -k2 -u -r
check 'missing fields tie stably' $'z\na\nx:1' $'z\nx:1\na\n' -t: -k2
check 'raw selected-field ties are also stable' $'c:X\nb:X\na:Y' $'c:X\na:Y\nb:X\n' -t: -k2 --code-point
first=$(printf 'b:1\na:1\nb:2\na:2\n' | "$CLI" -t: -k1 -r)
if [[ $? -ne 0 ]]; then exit 1; fi
check 'stable second pass retains first-pass order within ties' $'b:1\na:1\nb:2\na:2' "$first"$'\n' -t: -k2

# Independent finite witness: integer groups with deliberately shuffled arrival
# order. Expected output is generated by integer grouping, without calling the
# collator, its comparator, or its key builder. Exercise more than tiny qsorts.
work=$(mktemp -d) || exit 1
trap 'rm -r -- "$work"' EXIT
luajit - "$work" <<'LUA'
local root=assert(arg[1])
local input=assert(io.open(root..'/input','w'))
for i=1,5000 do input:write(string.format('record%05d:%d\n',i,(i*37)%17)) end
assert(input:close())
for _,descending in ipairs({false,true}) do
  for _,unique in ipairs({false,true}) do
    local name=(descending and 'desc' or 'asc')..(unique and '-unique' or '')
    local out=assert(io.open(root..'/'..name,'w'))
    for step=0,16 do
      local group=descending and 16-step or step
      for i=1,5000 do
        if (i*37)%17==group then
          out:write(string.format('record%05d:%d\n',i,group))
          if unique then break end
        end
      end
    end
    assert(out:close())
  end
end
LUA
if [[ $? -ne 0 ]]; then exit 1; fi
for direction in asc desc; do
	for unique in '' '-unique'; do
		flags=(-t: -k2)
		[[ $direction == desc ]] && flags+=(-r)
		[[ -n $unique ]] && flags+=(-u)
		if "$CLI" "${flags[@]}" "$work/input" > "$work/actual" && cmp -s "$work/actual" "$work/$direction$unique"; then
			PASS=$((PASS+1))
		else
			printf 'FAIL: 5000-row stability %s%s\n' "$direction" "$unique" >&2
			FAIL=$((FAIL+1))
		fi
	done
done
echo "stable_sort: $PASS passed, $FAIL failed"
exit "$FAIL"
